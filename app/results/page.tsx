"use client";

import { useEffect, useMemo, useState } from "react";
import { useRouter } from "next/navigation";

type ResultData = {
  score: number;
  strengths: string[];
  weaknesses: string[];
  finalFeedback?: string;
};

export default function ResultsPage() {
  const router = useRouter();
  const [copied, setCopied] = useState(false);
  const [results, setResults] = useState<ResultData | null>(null);

  useEffect(() => {
    if (typeof window !== "undefined") {
      const raw = localStorage.getItem("careersetu.results");
      setResults(raw ? (JSON.parse(raw) as ResultData) : null);
    }
  }, []);

  useEffect(() => {
    if (!results) {
      router.replace("/");
    }
  }, [results, router]);

  const report = useMemo(() => {
    if (!results) {
      return null;
    }

    const parsedScore = parseScoreOutOfTen(results);
    const strengths = parseSectionItems(
      results.finalFeedback,
      ["strengths", "what you did well"],
      results.strengths,
    );
    const improvements = parseSectionItems(
      results.finalFeedback,
      ["areas to improve", "improvements", "weaknesses"],
      results.weaknesses,
    );

    // Extract or estimate skill scores from feedback
    const skillScores = extractSkillScores(results.finalFeedback, parsedScore);

    return {
      score: parsedScore,
      strengths,
      improvements,
      skillScores,
      encouragement: encouragementMessage(parsedScore),
    };
  }, [results]);

  const shareResults = async () => {
    if (!report || !results) {
      return;
    }
    const text = [
      "CareerSetu AI Interview Report",
      `Overall Score: ${report.score}/10`,
      "",
      "Strengths:",
      ...report.strengths.map((item) => `- ${item}`),
      "",
      "Areas to Improve:",
      ...report.improvements.map((item) => `- ${item}`),
      "",
      `Encouragement: ${report.encouragement}`,
      results.finalFeedback ? `\nFinal Feedback:\n${results.finalFeedback}` : "",
    ]
      .filter(Boolean)
      .join("\n");

    await navigator.clipboard.writeText(text);
    setCopied(true);
    window.setTimeout(() => setCopied(false), 1500);
  };

  const downloadResults = () => {
    if (!report || !results) {
      return;
    }
    
    const text = [
      "CareerSetu AI Interview Report",
      "=".repeat(40),
      `Date: ${new Date().toLocaleDateString()}`,
      `Overall Score: ${report.score}/10`,
      "",
      "Skill Assessment:",
      `• Communication: ${report.skillScores.communication}/10`,
      `• Technical Knowledge: ${report.skillScores.technical}/10`,
      `• Confidence: ${report.skillScores.confidence}/10`,
      "",
      "Strengths:",
      ...report.strengths.map((item) => `✓ ${item}`),
      "",
      "Areas to Improve:",
      ...report.improvements.map((item) => `→ ${item}`),
      "",
      "Encouragement:",
      report.encouragement,
      "",
      "Final Feedback:",
      results.finalFeedback || "No detailed feedback available.",
      "=".repeat(40),
      "Generated by CareerSetu AI - Your smart bridge to a successful career"
    ]
      .filter(Boolean)
      .join("\n");

    const blob = new Blob([text], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `careersetu-interview-report-${new Date().toISOString().split('T')[0]}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  if (!report || !results) {
    return null;
  }

  return (
    <section className="mx-auto w-full max-w-5xl px-4 py-8 sm:px-6 sm:py-12 animate-fade-in">
      <div className="rounded-3xl border border-blue-100 bg-white p-6 shadow-xl shadow-blue-100/50 sm:p-10">
        <p className="text-sm font-semibold uppercase tracking-[0.2em] text-blue-600">
          CareerSetu AI Report Card
        </p>
        <h1 className="mt-3 text-3xl font-bold text-blue-950 sm:text-4xl">Interview Results</h1>
        <p className="mt-2 text-slate-600">Your comprehensive performance analysis and feedback.</p>

        {/* Celebration Banner */}
        {report.score >= 7 && (
          <div className="mt-6 animate-fade-in rounded-2xl border border-green-200 bg-gradient-to-r from-green-50 to-green-100 p-4 text-center">
            <div className="flex items-center justify-center gap-2">
              <span className="text-2xl animate-bounce">🎉</span>
              <span className="text-lg font-semibold text-green-800">Great job!</span>
            </div>
            <p className="mt-1 text-sm text-green-700">Excellent performance! You're interview-ready.</p>
          </div>
        )}

        {/* Circular Score Display */}
        <div className="mt-8 flex justify-center">
          <div className="relative">
            <div className={`relative flex h-32 w-32 items-center justify-center rounded-full sm:h-40 sm:w-40 ${
              report.score >= 7 
                ? 'bg-green-100' 
                : report.score >= 5 
                ? 'bg-orange-100' 
                : 'bg-red-100'
            }`}>
              <div className={`absolute inset-2 rounded-full ${
                report.score >= 7 
                  ? 'bg-green-500' 
                  : report.score >= 5 
                  ? 'bg-orange-500' 
                  : 'bg-red-500'
              }`} />
              <div className="relative z-10 text-center">
                <p className="text-3xl font-bold text-white sm:text-4xl">{report.score}</p>
                <p className="text-sm font-medium text-white/90">/10</p>
              </div>
            </div>
            <div className="mt-3 text-center">
              <span className={`inline-flex rounded-full px-3 py-1 text-sm font-semibold ${
                report.score >= 7 
                  ? 'bg-green-100 text-green-800' 
                  : report.score >= 5 
                  ? 'bg-orange-100 text-orange-800' 
                  : 'bg-red-100 text-red-800'
              }`}>
                {report.score >= 7 ? 'Excellent' : report.score >= 5 ? 'Good' : 'Needs Improvement'}
              </span>
            </div>
          </div>
        </div>

        {/* Skill Progress Bars */}
        <div className="mt-10 space-y-4">
          <h2 className="text-xl font-semibold text-blue-950">Skill Assessment</h2>
          <div className="space-y-4">
            <ProgressBar 
              label="Communication" 
              score={report.skillScores.communication} 
              color="blue"
            />
            <ProgressBar 
              label="Technical Knowledge" 
              score={report.skillScores.technical} 
              color="purple"
            />
            <ProgressBar 
              label="Confidence" 
              score={report.skillScores.confidence} 
              color="green"
            />
          </div>
        </div>

        {/* Strengths and Improvements */}
        <div className="mt-10 grid gap-6 sm:grid-cols-2">
          <div className="rounded-2xl border border-green-100 bg-green-50/50 p-5">
            <h2 className="text-lg font-semibold text-green-900">Strengths</h2>
            <ul className="mt-3 space-y-2 text-sm">
              {report.strengths.map((item) => (
                <li key={item} className="flex items-start gap-2">
                  <span className="inline-flex h-5 w-5 shrink-0 items-center justify-center rounded-full bg-green-100 text-green-700 text-xs font-bold">
                    ✓
                  </span>
                  <span className="text-slate-700">{item}</span>
                </li>
              ))}
            </ul>
          </div>
          
          <div className="rounded-2xl border border-orange-100 bg-orange-50/60 p-5">
            <h2 className="text-lg font-semibold text-orange-900">Areas to Improve</h2>
            <ul className="mt-3 space-y-2 text-sm">
              {report.improvements.map((item) => (
                <li key={item} className="flex items-start gap-2">
                  <span className="inline-flex h-5 w-5 shrink-0 items-center justify-center rounded-full bg-orange-100 text-orange-700 text-xs font-bold">
                    →
                  </span>
                  <span className="text-slate-700">{item}</span>
                </li>
              ))}
            </ul>
          </div>
        </div>

        {/* Encouragement */}
        <article className="mt-6 rounded-2xl border border-blue-100 bg-blue-50/40 p-5">
          <h2 className="text-lg font-semibold text-blue-900">Encouragement</h2>
          <p className="mt-2 text-slate-700">{report.encouragement}</p>
        </article>

        {/* Action Buttons */}
        <div className="mt-8 flex flex-wrap gap-3">
          <button
            type="button"
            onClick={downloadResults}
            className="rounded-xl bg-green-600 px-6 py-3 font-semibold text-white transition duration-200 hover:-translate-y-0.5 hover:scale-[1.01] hover:bg-green-700"
          >
            Download Results
          </button>
          <button
            type="button"
            onClick={() => router.push("/interview")}
            className="rounded-xl bg-blue-600 px-6 py-3 font-semibold text-white transition duration-200 hover:-translate-y-0.5 hover:scale-[1.01] hover:bg-blue-700"
          >
            Try Again
          </button>
          <button
            type="button"
            onClick={shareResults}
            className="rounded-xl border border-blue-200 bg-white px-6 py-3 font-semibold text-blue-700 transition duration-200 hover:-translate-y-0.5 hover:scale-[1.01] hover:bg-blue-50"
          >
            {copied ? "Copied!" : "Share Results"}
          </button>
        </div>
      </div>
    </section>
  );
}

function ResultCard({
  title,
  items,
  icon,
  tone,
}: {
  title: string;
  items: string[];
  icon: "check" | "warn";
  tone: "green" | "orange";
}) {
  const styles =
    tone === "green"
      ? "border-green-100 bg-green-50/50 text-green-900"
      : "border-orange-100 bg-orange-50/60 text-orange-900";
  const iconStyles =
    tone === "green"
      ? "bg-green-100 text-green-700"
      : "bg-orange-100 text-orange-700";

  return (
    <article className={`rounded-2xl border p-5 ${styles}`}>
      <h2 className="text-lg font-semibold">{title}</h2>
      <ul className="mt-3 space-y-2 text-sm">
        {items.map((item) => (
          <li key={item} className="flex items-start gap-2 rounded-lg bg-white/80 p-2.5 text-slate-700">
            <span className={`inline-flex h-5 w-5 shrink-0 items-center justify-center rounded-full text-xs font-bold ${iconStyles}`}>
              {icon === "check" ? "✓" : "!"}
            </span>
            <span>{item}</span>
          </li>
        ))}
      </ul>
    </article>
  );
}

function parseScoreOutOfTen(results: ResultData): number {
  const scoreFromFeedback = results.finalFeedback?.match(/(\d+(?:\.\d+)?)\s*\/\s*10/i);
  if (scoreFromFeedback) {
    return Number(scoreFromFeedback[1]);
  }
  if (results.score > 10) {
    return Number((results.score / 10).toFixed(1));
  }
  return Number(results.score.toFixed(1));
}

function parseSectionItems(
  feedback: string | undefined,
  headings: string[],
  fallback: string[],
): string[] {
  if (!feedback) {
    return fallback.slice(0, 3);
  }

  const lines = feedback
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);

  const startIndex = lines.findIndex((line) =>
    headings.some((heading) => line.toLowerCase().includes(heading)),
  );
  if (startIndex === -1) {
    return fallback.slice(0, 3);
  }

  const items: string[] = [];
  for (let index = startIndex + 1; index < lines.length; index += 1) {
    const line = lines[index];
    if (line.toLowerCase().includes("strength") || line.toLowerCase().includes("improv")) {
      if (items.length > 0) {
        break;
      }
    }
    if (/^[-*•]/.test(line) || /^\d+[.)]/.test(line)) {
      items.push(line.replace(/^[-*•]\s*/, "").replace(/^\d+[.)]\s*/, ""));
    }
    if (items.length === 3) {
      break;
    }
  }

  return items.length > 0 ? items : fallback.slice(0, 3);
}

function extractSkillScores(feedback: string | undefined, overallScore: number): {
  communication: number;
  technical: number;
  confidence: number;
} {
  // Default scores based on overall performance
  let communication = overallScore;
  let technical = overallScore;
  let confidence = overallScore;

  if (feedback) {
    // Try to extract specific skill mentions from feedback
    const feedbackLower = feedback.toLowerCase();
    
    // Look for communication keywords
    if (feedbackLower.includes('communication') || feedbackLower.includes('speaking') || feedbackLower.includes('clear')) {
      communication = Math.min(10, overallScore + 1);
    }
    if (feedbackLower.includes('unclear') || feedbackLower.includes('mumbled') || feedbackLower.includes('hesitant')) {
      communication = Math.max(1, overallScore - 1);
    }
    
    // Look for technical keywords
    if (feedbackLower.includes('technical') || feedbackLower.includes('knowledge') || feedbackLower.includes('skills')) {
      technical = Math.min(10, overallScore + 1);
    }
    if (feedbackLower.includes('lacking technical') || feedbackLower.includes('improve knowledge')) {
      technical = Math.max(1, overallScore - 1);
    }
    
    // Look for confidence keywords
    if (feedbackLower.includes('confident') || feedbackLower.includes('poised') || feedbackLower.includes('assured')) {
      confidence = Math.min(10, overallScore + 1);
    }
    if (feedbackLower.includes('nervous') || feedbackLower.includes('anxious') || feedbackLower.includes('lacked confidence')) {
      confidence = Math.max(1, overallScore - 1);
    }
  }

  // Add some variation to make it more realistic
  communication = Math.round(communication * 10) / 10;
  technical = Math.round(technical * 10) / 10;
  confidence = Math.round(confidence * 10) / 10;

  return { communication, technical, confidence };
}

function ProgressBar({ label, score, color }: {
  label: string;
  score: number;
  color: 'blue' | 'purple' | 'green';
}) {
  const colorClasses = {
    blue: 'bg-blue-500',
    purple: 'bg-purple-500',
    green: 'bg-green-500'
  };

  const bgClasses = {
    blue: 'bg-blue-100',
    purple: 'bg-purple-100',
    green: 'bg-green-100'
  };

  return (
    <div className="space-y-2">
      <div className="flex justify-between items-center">
        <span className="text-sm font-medium text-slate-700">{label}</span>
        <span className="text-sm font-semibold text-slate-900">{score}/10</span>
      </div>
      <div className="relative">
        <div className={`h-2 w-full rounded-full ${bgClasses[color]}`}>
          <div 
            className={`h-2 rounded-full ${colorClasses[color]} transition-all duration-1000 ease-out`}
            style={{ width: `${(score / 10) * 100}%` }}
          />
        </div>
      </div>
    </div>
  );
}

function encouragementMessage(score: number): string {
  if (score >= 8.5) {
    return "Excellent momentum. You are interview-ready and can now focus on fine-tuning impact stories.";
  }
  if (score >= 7) {
    return "Strong effort. With a little more structure and confidence, you can perform at top-tier level.";
  }
  return "Good start. Keep practicing with short, focused answers and your confidence will improve quickly.";
}
